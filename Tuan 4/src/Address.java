public class Address {
    int houseNumber;
    String street;
    String district;
    String city;
    String country;
    public Address(int houseNumber,String street, String district, String city, String country){
        this.houseNumber = houseNumber;
        this.street = street;
        this.district = district;
        this.city = city;
        this.country = country;
    }
}
